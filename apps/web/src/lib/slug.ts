/**
 * Convert freeform text to a URL-safe slug.
 * Used for oracle queries, collections, and anywhere user input becomes a URL.
 */
export function slugify(text: string): string {
  return text
    .toLowerCase()
    .trim()
    .replace(/[^\w\s-]/g, "")
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");
}
